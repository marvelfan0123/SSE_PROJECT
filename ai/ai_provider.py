"""AI Provider Abstraction Layer supporting Google Gemini API and Local Ollama."""
from __future__ import annotations
import json
import logging
import os
from abc import ABC, abstractmethod
from typing import Any, Dict, Optional

logger = logging.getLogger("vulnx.ai.provider")


class AIProvider(ABC):
    """Abstract base class for LLM inference providers."""

    @abstractmethod
    def is_available(self) -> bool:
        """Check if provider credentials/daemon are available."""
        pass

    @abstractmethod
    def generate(self, prompt: str, system_prompt: str = "", json_mode: bool = True) -> str:
        """Generate response text from model."""
        pass


class GeminiProvider(AIProvider):
    """Google Gemini API Provider using google-genai SDK."""

    def __init__(self, api_key: Optional[str] = None, model: str = "gemini-2.0-flash"):
        self.api_key = api_key or os.getenv("GEMINI_API_KEY", "").strip()
        self.model_name = model or os.getenv("GEMINI_MODEL", "gemini-2.0-flash")

    def is_available(self) -> bool:
        return bool(self.api_key)

    def generate(self, prompt: str, system_prompt: str = "", json_mode: bool = True) -> str:
        if not self.is_available():
            raise RuntimeError("GEMINI_API_KEY is not configured in environment.")

        try:
            from google import genai
            client = genai.Client(api_key=self.api_key)
            config = {}
            if json_mode:
                config["response_mime_type"] = "application/json"
            if system_prompt:
                config["system_instruction"] = system_prompt

            response = client.models.generate_content(
                model=self.model_name,
                contents=prompt,
                config=config if config else None
            )
            return response.text
        except Exception as exc:
            logger.error(f"Gemini API generation failed: {exc}")
            raise


class OllamaProvider(AIProvider):
    """Local Ollama LLM provider for air-gapped / offline enterprise environments."""

    def __init__(self, host: str = "http://localhost:11434", model: str = "qwen2.5-coder:7b"):
        self.host = host or os.getenv("OLLAMA_HOST", "http://localhost:11434")
        self.model = model or os.getenv("OLLAMA_MODEL", "qwen2.5-coder:7b")

    def is_available(self) -> bool:
        try:
            import urllib.request
            req = urllib.request.Request(f"{self.host}/api/tags")
            with urllib.request.urlopen(req, timeout=2) as resp:
                return resp.status == 200
        except Exception:
            return False

    def generate(self, prompt: str, system_prompt: str = "", json_mode: bool = True) -> str:
        import urllib.request
        payload = {
            "model": self.model,
            "prompt": prompt,
            "system": system_prompt,
            "stream": False
        }
        if json_mode:
            payload["format"] = "json"

        req = urllib.request.Request(
            f"{self.host}/api/generate",
            data=json.dumps(payload).encode("utf-8"),
            headers={"Content-Type": "application/json"}
        )
        try:
            with urllib.request.urlopen(req, timeout=60) as resp:
                data = json.loads(resp.read().decode("utf-8"))
                return data.get("response", "")
        except Exception as exc:
            logger.error(f"Ollama generation failed: {exc}")
            raise


