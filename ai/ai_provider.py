def get_ai_provider() -> AIProvider:
    """Factory returning active AI provider based on configuration."""
    provider_type = os.getenv("VULNX_AI_PROVIDER", "auto").lower()

    if provider_type == "ollama":
        p = OllamaProvider()
        if p.is_available():
            return p
    elif provider_type == "gemini":
        p = GeminiProvider()
        if p.is_available():
            return p

    # Auto mode: try Gemini first, then Ollama, fallback to deterministic
    gemini = GeminiProvider()
    if gemini.is_available():
        return gemini

    ollama = OllamaProvider()
    if ollama.is_available():
        return ollama

    return FallbackDeterministicProvider()
