"""AI Response Validator and Schema Enforcer."""
from __future__ import annotations
import json
import logging
import re
from typing import Any, Dict, List, Optional

logger = logging.getLogger("vulnx.ai.validator")


class AIResponseValidator:
    """Validates raw LLM responses against expected schema and security constraints."""

    @staticmethod
    def parse_and_validate_json(raw_text: str, required_keys: List[str]) -> Dict[str, Any]:
        """Safely extract JSON from model text and verify required top-level keys."""
        cleaned = raw_text.strip()
        
        # Regex search for ```json { ... } ```
        match = re.search(r"```(?:json)?\s*(\{[\s\S]*?\})\s*```", cleaned)
        if match:
            cleaned = match.group(1).strip()
        elif cleaned.startswith("```"):
            cleaned = re.sub(r"^```(?:json)?\s*", "", cleaned)
            cleaned = re.sub(r"\s*```$", "", cleaned).strip()

        try:
            parsed = json.loads(cleaned)
        except json.JSONDecodeError as exc:
            # Fallback search for any { ... } block
            outer = re.search(r"(\{[\s\S]*\})", cleaned)
            if outer:
                try:
                    parsed = json.loads(outer.group(1))
                except Exception:
                    logger.warning(f"Failed to parse AI output as JSON: {exc}. Raw snippet: {cleaned[:150]}")
                    return {"error": f"Invalid JSON generated by model: {exc}", "raw_text": cleaned}
            else:
                return {"error": f"Invalid JSON generated by model: {exc}", "raw_text": cleaned}

        if not isinstance(parsed, dict):
            return {
                "error": "Model response was not a JSON dictionary",
                "raw_text": cleaned
            }

        missing = [k for k in required_keys if k not in parsed]
        if missing:
            logger.warning(f"AI response missing required schema keys: {missing}")
            for k in missing:
                parsed[k] = None

        return parsed
